import { notFound } from "next/navigation";
import { Button } from "@/components/animate-ui/components/buttons/button";
import { BookingSummaryCard } from "@/components/userComponent/payment/bookingSummaryCard";
import { loadPayment } from "@/components/userComponent/payment/loadPayment";
import { PageHeader } from "@/components/userComponent/shared/pageHeader";
import { ButtonLink } from "@/components/userComponent/shared/buttonLink";

type PageProps = {
  params: Promise<{ bookingCode: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
};

export default async function Page({ params, searchParams }: PageProps) {
  const { bookingCode } = await params;
  const data = loadPayment(bookingCode, await searchParams);
  if (!data) notFound();

  const { event, session, tiers, booking, promo } = data;

  return (
    <div className="mx-auto max-w-2xl space-y-8">
      <PageHeader
        eyebrow="Payment received"
        title="You're going to the show"
        description="Your e-tickets are ready. We've also emailed the booking confirmation."
      />
      <BookingSummaryCard event={event} session={session} tiers={tiers} booking={booking} promoCode={promo} />
      <div className="flex flex-wrap items-center gap-3">
        <ButtonLink href="/tickets" hoverScale={1.02} className="h-12 rounded-full px-6 text-base font-semibold">View e-tickets</ButtonLink>
        <Button variant="outline" disabled className="h-12 rounded-full px-6 text-base">
          Download invoice (PDF)
        </Button>
      </div>
      <p className="text-sm text-text-muted">The PDF invoice becomes available once invoices are generated by the backend.</p>
    </div>
  );
}
